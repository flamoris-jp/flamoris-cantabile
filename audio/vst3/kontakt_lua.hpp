#pragma once
#include <nlohmann/json.hpp>
#include <string>
namespace cantabile::audio::kontakt {
using nlohmann::json;
// Decimal escapes encode every UTF-8 byte, including quotes/backslashes/newlines.
// JSON escaping is not Lua escaping. No request text can become executable Lua.
std::string kontakt_lua_string(const std::string& value) {
    std::string text = "\"";
    for (unsigned char c : value) {
        text += '\\'; text += static_cast<char>('0' + c / 100);
        text += static_cast<char>('0' + (c / 10) % 10); text += static_cast<char>('0' + c % 10);
    }
    return text + '"';
}

std::string kontakt_lua(const json& request, const std::string& receipt) {
    std::string code = "-- Generated by Cantabile: explicit registered selection only.\nlocal ok = pcall(function()\n"
        "  for _, index in ipairs(Kontakt.get_instrument_indices()) do Kontakt.remove_instrument(index) end\n"
        "  local slot = Kontakt.load_instrument(" + kontakt_lua_string(request["instrument"].get<std::string>()) + ")\n";
    if (!request["snapshot"].is_null()) code += "  Kontakt.load_snapshot(slot, " + kontakt_lua_string(request["snapshot"].get<std::string>()) + ")\n";
    auto temporary = receipt; temporary += ".part";
    code += "  Kontakt.set_instrument_midi_channel(slot, 1)\n  assert(Kontakt.get_num_instruments() == 1)\nend)\n"
        "local receipt = assert(io.open(" + kontakt_lua_string(temporary) + ", \"wb\"))\n"
        "receipt:write(" + kontakt_lua_string(request["nonce"].get<std::string>()) + " .. (ok and \":ok\" or \":failed\"))\nreceipt:close()\n";
    code += "assert(os.rename(" + kontakt_lua_string(temporary) + ", " + kontakt_lua_string(receipt) + "))\n";
    return code;
}

}
